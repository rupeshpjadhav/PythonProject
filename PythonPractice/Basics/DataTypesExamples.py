# Python Data Types with Examples
# Python has several built-in data types. Each type is used to store different kinds of values.
# This file is a quick reference for common data types and their examples.

# 1. Integer
# Used for whole numbers.
num = 10
print("Integer:", num)

# 2. Float
# Used for decimal numbers.
price = 19.99
print("Float:", price)

# 3. String
# Used for text data.
name = "Rupesh"
print("String:", name)

# 4. Boolean
# Used for True/False values.
flag = True
print("Boolean:", flag)

# 5. List
# Ordered and mutable collection that allows duplicates.
fruits = ["apple", "banana", "cherry"]
print("List:", fruits)

# 6. Tuple
# Ordered and immutable collection.
point = (10, 20)
print("Tuple:", point)

# 7. Set
# Unordered collection of unique elements.
numbers = {1, 2, 3, 3, 4}
print("Set:", numbers)

# 8. Dictionary
# Stores data in key-value pairs.
student = {"name": "Alice", "age": 21, "city": "Pune"}
print("Dictionary:", student)

# 9. None
# Represents the absence of a value.
result = None
print("None:", result)

# 10. Complex numbers
# Numbers with a real and imaginary part.
complex_num = 2 + 3j
print("Complex:", complex_num)

# 11. Bytes
# A sequence of integers from 0 to 255.
byte_data = b"hello"
print("Bytes:", byte_data)

# 12. Range
# Sequence of numbers used in loops.
range_data = range(5)
print("Range:", list(range_data))

# Summary
# Python data types help us store and process different kinds of information.
# Choosing the correct type makes programs easier to understand and manage.
